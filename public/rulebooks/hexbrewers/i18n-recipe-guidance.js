function normalizeRecipeTranslation(value, replacements) {
  if (typeof value === 'string') return replacements.reduce((text, [from, to]) => text.replaceAll(from, to), value);
  if (Array.isArray(value)) return value.map(item => normalizeRecipeTranslation(item, replacements));
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, normalizeRecipeTranslation(child, replacements)]));
}

